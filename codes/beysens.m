% BEYSENS: produccion de rocio a partir de los MAT de vectorizacion.m.
% Configuracion: entrada data/modelo<modelo>/<anio>/meteo_<anio>.mat;
% salida out/vectors/model<modelo>/dew_grid_<anio>.mat (sin subcarpetas).
modelo = '8.5';
anios = 2026:2040;                % Intervalo de anios a procesar

raiz = fileparts(fileparts(mfilename('fullpath')));
destino = fullfile(raiz,'out','vectors',['model' modelo]);
a = 17.27; b = 237.7; V0 = 4.4;

for anio = anios(:)'
    entrada = fullfile(raiz,'data',['modelo' modelo],num2str(anio), ...
        sprintf('meteo_%d.mat',anio));
    M = load(entrada);
    campos = {'TaZ','HZ','WZ','CloudZ','prZ','puntos','altitud_m', ...
        'tiempo','tiempos_originales','limites_temporales','intervalos_3h','metadatos'};
    assert(all(isfield(M,campos)),'El MAT no tiene la estructura de vectorizacion.m.');
    T = numel(M.tiempo); N = size(M.puntos,1);
    assert(size(M.puntos,2)==4 && isequal(size(M.altitud_m),[N 1]), ...
        'Coordenadas o altitudes incompatibles con la malla.');
    for k = 1:5
        assert(isequal(size(M.(campos{k})),[T N]), ...
            'Dimensiones incorrectas en %s.',campos{k});
    end
    esperado = (datenum(anio+1,1,1)-datenum(anio,1,1))*8;
    assert(M.metadatos.anio==anio && T==esperado && ...
        all(abs(diff(M.tiempo(:))-1/8)<1e-8), ...
        'Se requiere el anio completo con intervalos de tres horas.');
    assert(strcmp(M.metadatos.unidades.TaZ,'degC') && ...
        strcmp(M.metadatos.unidades.HZ,'%') && ...
        strcmp(M.metadatos.unidades.WZ,'m/s') && ...
        strcmp(M.metadatos.unidades.CloudZ,'oktas') && ...
        strcmp(M.metadatos.unidades.prZ,'mm/3h') && ...
        strcmp(M.metadatos.unidades.altitud_m,'m'), 'Unidades inesperadas.');

    % Altitud real ya muestreada por vectorizacion.m en los TIFF Copernicus.
    % No se usa una cota fija, interpolacion ni sustitucion de faltantes.
    assert(isfield(M.metadatos,'fuentes_dem') && ...
        (~any(isfinite(M.altitud_m)) || ~isempty(M.metadatos.fuentes_dem)), ...
        'Las altitudes no tienen procedencia DEM registrada.');
    altitud_m = M.altitud_m;
    altitud_m(~isfinite(altitud_m)) = NaN;
    H = altitud_m'/1000;          % Beysens requiere altitud en kilometros.
    sin_altitud = sum(isnan(altitud_m));
    if sin_altitud>0
        warning('beysens:sinAltitud', ...
            '%d: %d/%d puntos sin altitud DEM; R y rocio_anual seran NaN.', ...
            anio,sin_altitud,N);
    end

    % Punto de rocio (degC). Puede calcularse incluso sin altitud disponible.
    validos_td = isfinite(M.TaZ) & isfinite(M.HZ) & ...
        M.HZ>0 & M.HZ<=100 & (b+M.TaZ)~=0;
    Td = nan(T,N);
    alpha = a.*M.TaZ(validos_td)./(b+M.TaZ(validos_td)) + log(M.HZ(validos_td)/100);
    Td(validos_td) = b.*alpha./(a-alpha);
    Td(~isfinite(Td)) = NaN;

    % Ecuaciones y normalizacion R/4 del codigo Beysens anterior.
    term1 = 0.37 .* (1 + 0.204323.*H - 0.0238893.*H.^2 - ...
        (18.0132 - 1.04963.*H + 0.21891.*H.^2).*1e-3 .* Td);
    term2 = ((Td+273.15)/285).^4 .* (1-M.CloudZ/8);
    term3 = 0.045 .* (Td-M.TaZ) .* (1+100.*(1-exp(-(M.WZ/V0).^20)));
    R = term1.*term2 + term3;
    R(R<0) = 0;
    R = R/4;
    R = R .* (M.prZ<0.5);        % Se excluye tambien prZ == 0.5 mm/3h.
    validos = isfinite(Td) & isfinite(M.WZ) & M.WZ>=0 & ...
        isfinite(M.CloudZ) & M.CloudZ>=0 & M.CloudZ<=8 & ...
        isfinite(M.prZ) & M.prZ>=0 & isfinite(H);
    R(~validos | ~isfinite(R)) = NaN;

    % sum conserva NaN: un total incompleto no se presenta como anual valido.
    rocio_anual = sum(R,1)';
    precipitacion = M.prZ;
    precipitacion(~isfinite(precipitacion) | precipitacion<0) = NaN;
    precipitacion_anual = sum(precipitacion,1)';
    resultados_anio = [M.puntos(:,1:2),rocio_anual,precipitacion_anual,altitud_m];
    incompletos = sum(any(isnan(R),1) & isfinite(H));
    if incompletos>0
        warning('beysens:datosIncompletos', ...
            '%d: %d puntos con altitud tienen intervalos invalidos; total de rocio NaN.', ...
            anio,incompletos);
    end

    salida = struct('R',R,'Td',Td,'rocio_anual',rocio_anual, ...
        'precipitacion_anual',precipitacion_anual,'altitud_m',altitud_m, ...
        'resultados_anio',resultados_anio,'puntos',M.puntos,'tiempo',M.tiempo, ...
        'tiempos_originales',M.tiempos_originales, ...
        'limites_temporales',M.limites_temporales, ...
        'intervalos_3h',M.intervalos_3h,'metadatos',M.metadatos);
    salida.metadatos.beysens = struct('modelo',modelo,'a',a,'b',b,'V0',V0, ...
        'unidad_H','km','unidad_R','mm/intervalo de 3 h (R/4 original)', ...
        'unidad_Td','degC','unidad_acumulados','mm', ...
        'umbral_precipitacion_mm',0.5,'divisor_R',4, ...
        'columnas_resultados',{{'latitud','longitud','rocio_anual', ...
        'precipitacion_anual','altitud_m'}}, ...
        'faltantes','NaN; sumas anuales estrictas, sin omitir intervalos', ...
        'fuente_meteo',entrada);
    if ~exist(destino,'dir'), mkdir(destino); end
    archivo = fullfile(destino,sprintf('dew_grid_%d.mat',anio));
    save(archivo,'-struct','salida','-v7');
    fprintf('%d: guardado %s (%d x %d; %d totales de rocio disponibles).\n', ...
        anio,archivo,T,N,sum(isfinite(rocio_anual)));
end
